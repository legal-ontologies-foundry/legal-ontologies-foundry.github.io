#!/usr/bin/env python3
"""Publish the Foundry's GitHub activity as ordinary website pages.

Writes docs/activity/*.md so that people without GitHub accounts can read
open proposals, discussions, the decision log, and the member list.
Run by the deploy workflow on every push and every hour.

Data comes from the GitHub API (REST for issues and pull requests, GraphQL for
Discussions) using GITHUB_TOKEN. If the API cannot be reached, the pages are
still written, with a notice, so the site always builds.

Never edit docs/activity/ by hand; it is regenerated on every build.
"""
from datetime import datetime, timezone
from pathlib import Path
import html
import json
import os
import re
import sys
import urllib.error
import urllib.request

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "activity"
MEMBERS = ROOT / "community" / "members.yml"
REPO = os.environ.get("GITHUB_REPOSITORY", "legal-ontologies-foundry/legal-ontologies-foundry.github.io")
TOKEN = os.environ.get("GITHUB_TOKEN", "")
API = "https://api.github.com"
GH = f"https://github.com/{REPO}"
GENERATED = "<!-- GENERATED by scripts/build_activity.py. Do not edit; it is rebuilt every hour. -->"
NOW = datetime.now(timezone.utc)


# ---------------------------------------------------------------- fetching

def _request(url, data=None):
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "lof-activity"}
    if TOKEN:
        headers["Authorization"] = f"Bearer {TOKEN}"
    req = urllib.request.Request(url, data=data, headers=headers)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode())


def rest_all(path):
    items, page = [], 1
    while page <= 10:
        sep = "&" if "?" in path else "?"
        batch = _request(f"{API}{path}{sep}per_page=100&page={page}")
        items += batch
        if len(batch) < 100:
            break
        page += 1
    return items


DISCUSSIONS_QUERY = """
query($owner: String!, $name: String!) {
  repository(owner: $owner, name: $name) {
    discussions(first: 50, orderBy: {field: UPDATED_AT, direction: DESC}) {
      nodes {
        number title url createdAt updatedAt closed
        author { login }
        category { name }
        answerChosenAt
        body
        comments(first: 50) { totalCount nodes { author { login } createdAt body } }
      }
    }
  }
}"""


def discussions():
    owner, name = REPO.split("/")
    payload = json.dumps({"query": DISCUSSIONS_QUERY, "variables": {"owner": owner, "name": name}}).encode()
    data = _request(f"{API}/graphql", data=payload)
    if "errors" in data:
        raise RuntimeError(data["errors"][0].get("message", "GraphQL error"))
    return data["data"]["repository"]["discussions"]["nodes"]


# ---------------------------------------------------------------- formatting

def day(ts):
    return datetime.fromisoformat(ts.replace("Z", "+00:00")).strftime("%d %B %Y").lstrip("0") if ts else ""


def who(user):
    return (user or {}).get("login") or "a former member"


def safe(text):
    """User-written Markdown, shown as Markdown but with any HTML neutralized."""
    text = (text or "").replace("\r\n", "\n").strip()
    text = html.escape(text, quote=False)
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    return text or "*(no description)*"


def excerpt(text, limit=500):
    text = re.sub(r"(?m)^\s*#+\s*", "", text or "")
    text = re.sub(r"\s+", " ", re.sub(r"[>*_`|]", "", text)).strip()
    text = html.escape(text, quote=False)
    return (text[:limit].rsplit(" ", 1)[0] + "...") if len(text) > limit else (text or "No description.")


def indent(text, n=4):
    return "\n".join((" " * n + line) if line else "" for line in text.split("\n"))


def labels(item):
    names = [l["name"] for l in item.get("labels", [])]
    return " ".join(f"`{n}`" for n in names)


def header(title, intro):
    stamp = NOW.strftime("%d %B %Y, %H:%M UTC").lstrip("0")
    return f"{GENERATED}\n# {title}\n\n{intro}\n\n*Updated {stamp}.*\n\n"


def notice(what, err):
    return (f'!!! warning "{what} could not be loaded"\n'
            f"    The site was built without access to GitHub ({err}). It will refresh within the hour.\n"
            f"    Meanwhile you can see everything directly on [GitHub]({GH}).\n\n")


PARTICIPATE = ("You do not need a GitHub account to take part: see "
               "[how to participate](../contributing.md). Links to GitHub open the full record.")


# ---------------------------------------------------------------- pages

def page_proposals(issues, pulls, err):
    s = header("Open proposals and questions",
               "Everything currently open for comment in the Foundry: proposed changes to the "
               "site and the ontologies, and open questions and tasks. " + PARTICIPATE)
    if err:
        return s + notice("Proposals", err)
    open_prs = [p for p in pulls if p["state"] == "open"]
    open_issues = [i for i in issues if i["state"] == "open" and "pull_request" not in i]
    s += f"## Proposed changes ({len(open_prs)})\n\n"
    s += ("A proposed change is a set of edits awaiting review. Drafts are still being prepared; "
          "the others are ready for decision.\n\n") if open_prs else "There are no proposed changes open right now.\n\n"
    for p in sorted(open_prs, key=lambda x: x["created_at"], reverse=True):
        status = "draft, still being prepared" if p.get("draft") else "ready for review"
        s += (f"### {html.escape(p['title'])} {{ #change-{p['number']} }}\n\n"
              f"Proposed by **{who(p['user'])}** on {day(p['created_at'])} · {status} · "
              f"[view and comment on GitHub]({p['html_url']})\n\n"
              f"{excerpt(p.get('body'))}\n\n"
              f'??? note "Full description"\n{indent(safe(p.get("body")))}\n\n')
    s += f"## Open questions and tasks ({len(open_issues)})\n\n"
    for i in sorted(open_issues, key=lambda x: x["updated_at"], reverse=True):
        tag = f" · {labels(i)}" if i.get("labels") else ""
        s += (f"### {html.escape(i['title'])} {{ #issue-{i['number']} }}\n\n"
              f"Raised by **{who(i['user'])}** on {day(i['created_at'])} · "
              f"{i['comments']} comment{'s' if i['comments'] != 1 else ''}{tag} · "
              f"[view and comment on GitHub]({i['html_url']})\n\n"
              f"{excerpt(i.get('body'))}\n\n"
              f'??? note "Full text"\n{indent(safe(i.get("body")))}\n\n')
    return s


def page_discussions(items, err):
    s = header("Discussions",
               "Recent conversations in the Foundry, newest activity first. " + PARTICIPATE)
    if err:
        return s + notice("Discussions", err)
    if not items:
        return s + "No discussions yet. Start one through the participation page.\n"
    for d in items:
        n = d["comments"]["totalCount"]
        s += (f"## {html.escape(d['title'])} {{ #discussion-{d['number']} }}\n\n"
              f"**{who(d['author'])}** in *{d['category']['name']}* · started {day(d['createdAt'])} · "
              f"{n} repl{'ies' if n != 1 else 'y'} · last activity {day(d['updatedAt'])} · "
              f"[view and reply on GitHub]({d['url']})\n\n"
              f"{safe(d['body'])}\n\n")
        for c in d["comments"]["nodes"]:
            s += f'??? quote "{who(c["author"])}, {day(c["createdAt"])}"\n{indent(safe(c["body"]))}\n\n'
        s += "---\n\n"
    return s


def page_decisions(issues, pulls, err):
    s = header("Decision log",
               "Every change adopted and every question closed, newest first. Adopted changes "
               "are merged into the site or the ontologies by a coordinator after review, as set out in "
               "[Governance](../about/governance.md).")
    if err:
        return s + notice("The decision log", err)
    rows = []
    for p in pulls:
        if p.get("merged_at"):
            rows.append((p["merged_at"], "Adopted", p, "change"))
        elif p["state"] == "closed":
            rows.append((p["closed_at"], "Withdrawn or declined", p, "change"))
    for i in issues:
        if "pull_request" in i or i["state"] != "closed":
            continue
        outcome = "Not pursued" if i.get("state_reason") == "not_planned" else "Resolved"
        rows.append((i["closed_at"], outcome, i, "question"))
    if not rows:
        return s + "No decisions recorded yet.\n"
    s += "| Date | Outcome | Item | Proposed by |\n|---|---|---|---|\n"
    for ts, outcome, item, kind in sorted(rows, key=lambda r: r[0], reverse=True):
        title = html.escape(item["title"]).replace("|", "\\|")
        s += f"| {day(ts)} | {outcome} | [{title}]({item['html_url']}) ({kind} #{item['number']}) | {who(item['user'])} |\n"
    return s


def page_members():
    s = header("Members",
               "People taking part in the Foundry. Anyone may join; a GitHub account is optional. "
               "See [Governance](../about/governance.md) for what membership involves.")
    try:
        members = yaml.safe_load(MEMBERS.read_text()) or []
    except FileNotFoundError:
        members = []
    order = {"founding coordinator": 0, "coordinator": 1, "member": 2}
    s += "| Name | Affiliation | Role | Since |\n|---|---|---|---|\n"
    for m in sorted(members, key=lambda m: (order.get(m.get("role", "member"), 3), m["name"])):
        name = html.escape(m["name"])
        if m.get("github"):
            name = f"[{name}](https://github.com/{m['github']})"
        s += f"| {name} | {html.escape(m.get('affiliation', ''))} | {m.get('role', 'member')} | {m.get('joined', '')} |\n"
    return s


def page_index(issues, pulls, disc, err_rest, err_disc):
    s = header("Foundry activity",
               "What is happening in the Foundry, readable without a GitHub account. These pages are "
               "rebuilt from the Foundry's GitHub records every hour.")
    if err_rest:
        s += notice("Activity", err_rest)
        open_prs = open_issues = adopted = "?"
    else:
        open_prs = sum(1 for p in pulls if p["state"] == "open")
        open_issues = sum(1 for i in issues if i["state"] == "open" and "pull_request" not in i)
        adopted = sum(1 for p in pulls if p.get("merged_at"))
    nd = "?" if err_disc else len(disc)
    s += ("| Page | What it shows | Now |\n|---|---|---|\n"
          f"| [Open proposals](proposals.md) | Proposed changes and open questions, open for comment | {open_prs} changes, {open_issues} questions |\n"
          f"| [Discussions](discussions.md) | Conversations, with replies | {nd} recent |\n"
          f"| [Decision log](decisions.md) | Changes adopted and questions closed | {adopted} changes adopted |\n"
          f"| [Members](members.md) | Who takes part | |\n")
    return s


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    issues = pulls = disc = []
    err_rest = err_disc = None
    try:
        issues = rest_all(f"/repos/{REPO}/issues?state=all")
        pulls = rest_all(f"/repos/{REPO}/pulls?state=all")
    except (urllib.error.URLError, OSError, ValueError) as e:
        err_rest = getattr(e, "reason", None) or str(e)
    try:
        disc = discussions()
    except (urllib.error.URLError, OSError, ValueError, RuntimeError, KeyError, TypeError) as e:
        err_disc = getattr(e, "reason", None) or str(e)
    pages = {
        "index.md": page_index(issues, pulls, disc, err_rest, err_disc),
        "proposals.md": page_proposals(issues, pulls, err_rest),
        "discussions.md": page_discussions(disc, err_disc),
        "decisions.md": page_decisions(issues, pulls, err_rest),
        "members.md": page_members(),
    }
    for name, text in pages.items():
        (OUT / name).write_text(text)
    print(f"activity: {len(issues)} issues and pull requests, {len(pulls)} pull requests, "
          f"{len(disc)} discussions" + (f"; REST unavailable: {err_rest}" if err_rest else "")
          + (f"; discussions unavailable: {err_disc}" if err_disc else ""))


if __name__ == "__main__":
    main()
