#!/usr/bin/env python3
"""Publish the Foundry's GitHub activity as ordinary website pages.

Writes docs/activity/*.md so that people without GitHub accounts can read
open proposals, discussions, the decision log, and the member list.
Run by the deploy workflow on every push and every hour.

Data comes from the GitHub API (REST for issues and pull requests, GraphQL for
Discussions) using GITHUB_TOKEN. If the API cannot be reached, the pages are
still written, with a notice, so the site always builds.

Never edit docs/activity/ by hand; it is regenerated on every build.
"""
from datetime import datetime, timezone
from pathlib import Path
import html
import json
import math
import os
import re
import sys
import urllib.error
import urllib.request

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "activity"
MEMBERS = ROOT / "community" / "members.yml"
FORMS = ROOT / "community" / "forms.yml"
RULES = ROOT / "community" / "decision-rules.json"
REPO = os.environ.get("GITHUB_REPOSITORY", "legal-ontologies-foundry/legal-ontologies-foundry.github.io")
TOKEN = os.environ.get("GITHUB_TOKEN", "")
API = "https://api.github.com"
GH = f"https://github.com/{REPO}"
GENERATED = "<!-- GENERATED by scripts/build_activity.py. Do not edit; it is rebuilt every hour. -->"
NOW = datetime.now(timezone.utc)


# ---------------------------------------------------------------- fetching

def _request(url, data=None):
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "lof-activity"}
    if TOKEN:
        headers["Authorization"] = f"Bearer {TOKEN}"
    req = urllib.request.Request(url, data=data, headers=headers)
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read().decode())


def rest_all(path):
    items, page = [], 1
    while page <= 10:
        sep = "&" if "?" in path else "?"
        batch = _request(f"{API}{path}{sep}per_page=100&page={page}")
        items += batch
        if len(batch) < 100:
            break
        page += 1
    return items


DISCUSSIONS_QUERY = """
query($owner: String!, $name: String!) {
  repository(owner: $owner, name: $name) {
    discussions(first: 50, orderBy: {field: UPDATED_AT, direction: DESC}) {
      nodes {
        number title url createdAt updatedAt closed
        author { login }
        category { name }
        answerChosenAt
        body
        comments(first: 50) { totalCount nodes { author { login } createdAt body } }
      }
    }
  }
}"""


def discussions():
    owner, name = REPO.split("/")
    payload = json.dumps({"query": DISCUSSIONS_QUERY, "variables": {"owner": owner, "name": name}}).encode()
    data = _request(f"{API}/graphql", data=payload)
    if "errors" in data:
        raise RuntimeError(data["errors"][0].get("message", "GraphQL error"))
    return data["data"]["repository"]["discussions"]["nodes"]


# ---------------------------------------------------------------- decisions

VOTE_LABELS = {"approve": "Approve", "object": "Object", "abstain": "Abstain"}


def load_members():
    try:
        return yaml.safe_load(MEMBERS.read_text()) or []
    except FileNotFoundError:
        return []


def load_rules():
    try:
        return json.loads(RULES.read_text())
    except FileNotFoundError:
        return None


def kind_of(pr, rules):
    if not rules or pr.get("draft") or pr["state"] != "open":
        return None
    names = {l["name"] for l in pr.get("labels", [])}
    kinds = [k for k, r in rules["kinds"].items() if r["label"] in names]
    return "substantive" if "substantive" in kinds else (kinds[0] if kinds else None)


def parse_time(ts):
    return datetime.fromisoformat(ts.replace("Z", "+00:00"))


def collect_votes(n, rules, members):
    """Website ballots (bot comments with a lof-vote marker) and GitHub reviews by voting members."""
    by_login = {str(m["github"]).lower(): m["name"] for m in members if m.get("github")}
    votes = []
    for r in rest_all(f"/repos/{REPO}/pulls/{n}/reviews"):
        who = by_login.get(((r.get("user") or {}).get("login") or "").lower())
        v = {"APPROVED": "approve", "CHANGES_REQUESTED": "object"}.get(r["state"])
        if who and v:
            votes.append({"voter": who, "vote": v, "at": r["submitted_at"], "via": "GitHub"})
    for c in rest_all(f"/repos/{REPO}/issues/{n}/comments"):
        app = (c.get("performed_via_github_app") or {}).get("slug")
        if app != rules["bot"] and (c.get("user") or {}).get("login") != rules["bot"] + "[bot]":
            continue
        m = re.search(r"<!-- lof-vote (\{.*?\}) -->", c.get("body") or "")
        if m:
            v = json.loads(m.group(1))
            votes.append({"voter": v["voter"], "vote": v["vote"], "at": c["created_at"], "via": "website"})
    return votes


def label_time(n, label):
    at = None
    for e in rest_all(f"/repos/{REPO}/issues/{n}/events"):
        if e.get("event") == "labeled" and (e.get("label") or {}).get("name") == label:
            at = parse_time(e["created_at"])
    return at


def tally(rules, kind, members, votes, opened, now):
    """Apply a rule. Kept identical to tally_() in website-forms/Voting.gs."""
    rule = rules["kinds"][kind]
    voting = [m["name"] for m in members if m.get("voting")]
    committee = [m["name"] for m in members if m.get("committee") and m.get("voting")]
    by_voter = {}
    for v in sorted(votes, key=lambda v: parse_time(v["at"])):
        if v["voter"] in voting and v["vote"] in VOTE_LABELS:
            by_voter[v["voter"]] = v
    lst = lambda k: [n for n in voting if n in by_voter and by_voter[n]["vote"] == k]
    approve, obj, abstain = lst("approve"), lst("object"), lst("abstain")
    committee_yes = [n for n in committee if n in approve]
    days_open = (now - opened).total_seconds() / 86400
    days_left = max(0, math.ceil(rule["comment_days"] - days_open))
    waiting = []
    if days_open < rule["comment_days"]:
        waiting.append(f"comment period: {days_left} day{'' if days_left == 1 else 's'} left")
    if rule.get("committee") == "all":
        missing = [n for n in committee if n not in committee_yes]
        if not committee or missing:
            waiting.append("approval from " + (", ".join(missing) or "the Operations Committee"))
    elif not committee_yes:
        waiting.append("approval from an Operations Committee member")
    if rule.get("objection_blocks") and obj:
        waiting.append("objection from " + ", ".join(obj))
    if rule.get("majority") and len(approve) <= len(obj):
        waiting.append("a majority of votes cast to approve")
    return {"passed": not waiting, "waiting": waiting, "days_left": days_left,
            "status": ("Waiting for " + "; ".join(waiting) + ".") if waiting else "Passed; it will be adopted at the next check.",
            "by_voter": by_voter, "approve": approve, "object": obj, "abstain": abstain}


def decisions_in_progress(pulls):
    rules, members = load_rules(), load_members()
    out = []
    for p in pulls:
        kind = kind_of(p, rules)
        if not kind:
            continue
        label = rules["kinds"][kind]["label"]
        opened = label_time(p["number"], label) or parse_time(p["created_at"])
        t = tally(rules, kind, members, collect_votes(p["number"], rules, members), opened, NOW)
        out.append((p, kind, opened, t))
    return rules, members, out


def section_decisions(rules, members, items):
    if not items:
        return ""
    voting = [m for m in members if m.get("voting")]
    s = (f"## Open for decision ({len(items)})\n\n"
         "These proposals are being decided now. Voting members vote with a personal ballot link "
         "emailed to them, or on GitHub; the count below is updated every hour. "
         "See [Governance](../about/governance.md).\n\n")
    for p, kind, opened, t in items:
        rule = rules["kinds"][kind]
        s += (f"### {html.escape(p['title'])} {{ #decision-{p['number']} }}\n\n"
              f"**{kind.capitalize()} change**, open for decision since {day(opened.isoformat())}. {rule['summary']}\n\n"
              f"**Status:** {t['status']}\n\n"
              "| Voting member | Vote | How |\n|---|---|---|\n")
        for m in voting:
            v = t["by_voter"].get(m["name"])
            who = html.escape(m["name"]) + (" (committee)" if m.get("committee") else "")
            s += f"| {who} | {VOTE_LABELS[v['vote']] if v else 'not yet voted'} | {('on ' + v['via']) if v else ''} |\n"
        s += f"\n{reply_links(p['html_url'])}\n\n"
    return s


# ---------------------------------------------------------------- formatting

def day(ts):
    return datetime.fromisoformat(ts.replace("Z", "+00:00")).strftime("%d %B %Y").lstrip("0") if ts else ""


def who(user):
    return (user or {}).get("login") or "a former member"


def safe(text):
    """User-written Markdown, shown as Markdown but with any HTML neutralized."""
    text = (text or "").replace("\r\n", "\n").strip()
    text = html.escape(text, quote=False)
    text = re.sub(r"<!--.*?-->", "", text, flags=re.S)
    return text or "*(no description)*"


def excerpt(text, limit=500):
    text = re.sub(r"(?m)^\s*#+\s*", "", text or "")
    text = re.sub(r"\s+", " ", re.sub(r"[>*_`|]", "", text)).strip()
    text = html.escape(text, quote=False)
    return (text[:limit].rsplit(" ", 1)[0] + "...") if len(text) > limit else (text or "No description.")


def indent(text, n=4):
    return "\n".join((" " * n + line) if line else "" for line in text.split("\n"))


def labels(item):
    names = [l["name"] for l in item.get("labels", [])]
    return " ".join(f"`{n}`" for n in names)


def header(title, intro):
    stamp = NOW.strftime("%d %B %Y, %H:%M UTC").lstrip("0")
    return f"{GENERATED}\n# {title}\n\n{intro}\n\n*Updated {stamp}.*\n\n"


def notice(what, err):
    return (f'!!! warning "{what} could not be loaded"\n'
            f"    The site was built without access to GitHub ({err}). It will refresh within the hour.\n"
            f"    Meanwhile you can see everything directly on [GitHub]({GH}).\n\n")


PARTICIPATE = ("You do not need a GitHub account to take part: see "
               "[how to participate](participate.md). Links to GitHub open the full record.")


def load_forms():
    try:
        f = yaml.safe_load(FORMS.read_text()) or {}
        return f if f.get("form_url") and f.get("prefill") and f.get("actions") else None
    except FileNotFoundError:
        return None


FORM = load_forms()


def form_link(action, item_url=None):
    """Link to the participation form, opened at the right section (and item, for comments)."""
    if not FORM:
        return None
    from urllib.parse import quote
    url = f"{FORM['form_url']}?usp=pp_url&{FORM['prefill']['action']}={quote(FORM['actions'][action])}"
    if item_url:
        url += f"&{FORM['prefill']['link']}={quote(item_url)}"
    return url


def reply_links(item_url, verb="comment"):
    own = form_link("comment", item_url)
    gh = f"[{verb} on GitHub]({item_url})"
    return f"[{verb} without GitHub]({own}) · {gh}" if own else f"[view and {verb} on GitHub]({item_url})"


# ---------------------------------------------------------------- pages

def page_proposals(issues, pulls, err, decisions=None):
    s = header("Open proposals and questions",
               "Everything currently open for comment in the Foundry: proposed changes to the "
               "site and the ontologies, and open questions and tasks. " + PARTICIPATE)
    if err:
        return s + notice("Proposals", err)
    open_prs = [p for p in pulls if p["state"] == "open"]
    open_issues = [i for i in issues if i["state"] == "open" and "pull_request" not in i]
    if decisions:
        s += section_decisions(*decisions)
    s += f"## Proposed changes ({len(open_prs)})\n\n"
    s += ("A proposed change is a set of edits awaiting review. Drafts are still being prepared; "
          "the others are ready for decision.\n\n") if open_prs else "There are no proposed changes open right now.\n\n"
    for p in sorted(open_prs, key=lambda x: x["created_at"], reverse=True):
        status = "draft, still being prepared" if p.get("draft") else "ready for review"
        s += (f"### {html.escape(p['title'])} {{ #change-{p['number']} }}\n\n"
              f"Proposed by **{who(p['user'])}** on {day(p['created_at'])} · {status} · "
              f"{reply_links(p['html_url'])}\n\n"
              f"{excerpt(p.get('body'))}\n\n"
              f'??? note "Full description"\n{indent(safe(p.get("body")))}\n\n')
    s += f"## Open questions and tasks ({len(open_issues)})\n\n"
    for i in sorted(open_issues, key=lambda x: x["updated_at"], reverse=True):
        tag = f" · {labels(i)}" if i.get("labels") else ""
        s += (f"### {html.escape(i['title'])} {{ #issue-{i['number']} }}\n\n"
              f"Raised by **{who(i['user'])}** on {day(i['created_at'])} · "
              f"{i['comments']} comment{'s' if i['comments'] != 1 else ''}{tag} · "
              f"{reply_links(i['html_url'])}\n\n"
              f"{excerpt(i.get('body'))}\n\n"
              f'??? note "Full text"\n{indent(safe(i.get("body")))}\n\n')
    return s


SITE = "https://legal-ontologies-foundry.github.io/"


def page_title(path):
    """Title of the site page that a page-comment thread belongs to.

    Comments left at the foot of a site page are stored as Discussions whose
    title is the page's path (for example 'odp/odp-001/').
    """
    if not re.fullmatch(r"[\w./-]*/", path):
        return None
    stem = path.strip("/")
    for f in (ROOT / "docs" / f"{stem}.md", ROOT / "docs" / stem / "index.md"):
        if f.is_file():
            for line in f.read_text().splitlines():
                if line.startswith("# "):
                    return line[2:].strip()
            return stem.rsplit("/", 1)[-1].replace("-", " ").capitalize()
    return None


def page_discussions(items, err):
    s = header("Discussions",
               "Recent conversations in the Foundry, newest activity first. " + PARTICIPATE)
    if err:
        return s + notice("Discussions", err)
    if not items:
        return s + "No discussions yet. Start one through the participation page.\n"
    for d in items:
        n = d["comments"]["totalCount"]
        page = page_title(d["title"])
        if page:
            title = f"Comments on the page: {page}"
            where = f"on the page [{html.escape(page)}]({SITE}{d['title'].lstrip('/')})"
        else:
            title, where = d["title"], f"in *{d['category']['name']}*"
        s += (f"## {html.escape(title)} {{ #discussion-{d['number']} }}\n\n"
              f"**{who(d['author'])}** {where} · started {day(d['createdAt'])} · "
              f"{n} repl{'ies' if n != 1 else 'y'} · last activity {day(d['updatedAt'])} · "
              f"{reply_links(d['url'], 'reply')}\n\n"
              f"{safe(d['body'])}\n\n")
        for c in d["comments"]["nodes"]:
            s += f'??? quote "{who(c["author"])}, {day(c["createdAt"])}"\n{indent(safe(c["body"]))}\n\n'
        s += "---\n\n"
    return s


def page_decisions(issues, pulls, err):
    s = header("Decision log",
               "Every change adopted and every question closed, newest first. Adopted changes "
               "are merged into the site or the ontologies by a coordinator after review, as set out in "
               "[Governance](../about/governance.md).")
    if err:
        return s + notice("The decision log", err)
    rows = []
    for p in pulls:
        if p.get("merged_at"):
            rows.append((p["merged_at"], "Adopted", p, "change"))
        elif p["state"] == "closed":
            rows.append((p["closed_at"], "Withdrawn or declined", p, "change"))
    for i in issues:
        if "pull_request" in i or i["state"] != "closed":
            continue
        outcome = "Not pursued" if i.get("state_reason") == "not_planned" else "Resolved"
        rows.append((i["closed_at"], outcome, i, "question"))
    if not rows:
        return s + "No decisions recorded yet.\n"
    s += "| Date | Outcome | Item | Proposed by |\n|---|---|---|---|\n"
    for ts, outcome, item, kind in sorted(rows, key=lambda r: r[0], reverse=True):
        title = html.escape(item["title"]).replace("|", "\\|")
        s += f"| {day(ts)} | {outcome} | [{title}]({item['html_url']}) ({kind} #{item['number']}) | {who(item['user'])} |\n"
    return s


def page_members():
    s = header("Members",
               "People taking part in the Foundry. Anyone may join; a GitHub account is optional. "
               "See [Governance](../about/governance.md) for what membership involves.")
    try:
        members = yaml.safe_load(MEMBERS.read_text()) or []
    except FileNotFoundError:
        members = []
    order = {"founding coordinator": 0, "coordinator": 1, "working group lead": 2, "member": 3}
    s += "| Name | Affiliation | Role | Votes on proposals | Since |\n|---|---|---|---|---|\n"
    for m in sorted(members, key=lambda m: (order.get(m.get("role", "member"), 3), m["name"])):
        name = html.escape(m["name"])
        if m.get("github"):
            name = f"[{name}](https://github.com/{m['github']})"
        votes = "yes, Operations Committee" if m.get("committee") and m.get("voting") else ("yes" if m.get("voting") else "")
        s += f"| {name} | {html.escape(m.get('affiliation', ''))} | {m.get('role', 'member')} | {votes} | {m.get('joined', '')} |\n"
    return s


